import { parse } from 'yaml'
import type { Animate, Theme } from './core.js'

export interface Config extends Theme {
  /** Origin of the running app, e.g. http://localhost:3000. */
  url: string
  /**
   * Plain paths are start points. Glob paths limit which links are followed:
   * `*` matches one segment (and one sample page is enough), `**` any depth.
   */
  routes: string[]
  /** Follow same-origin links from `routes`. Off: visit only `routes`. */
  crawl: boolean
  /** Upper bound on pages visited, so dynamic routes (/item/1, /item/2, ...) cannot run forever. */
  maxPages: number
  /** Path prefixes never visited, e.g. /admin. Logout links are always skipped. */
  ignore: string[]
  /** Viewport widths captured per route. */
  breakpoints: number[]
  /** Output directory for `<name>.bones.json` and `registry.ts`. */
  out: string
  /** ms to wait after load before capture. */
  wait: number
  /** Playwright browser channel, e.g. `chrome` to reuse installed Chrome instead of downloading Chromium. */
  channel?: string
  /** Cookies sent with every page, `name=value`. */
  cookies: string[]
}

const DEFAULTS: Config = {
  url: 'http://localhost:3000',
  routes: ['/'],
  crawl: true,
  maxPages: 50,
  ignore: [],
  breakpoints: [375, 768, 1280],
  out: './src/bones',
  wait: 800,
  cookies: [],
}

const THEME_KEYS = ['color', 'darkColor', 'shimmerColor', 'darkShimmerColor', 'speed'] as const
const ANIMATIONS: Animate[] = ['pulse', 'shimmer', 'solid']

function fail(msg: string): never {
  throw new Error(`jiplak.yaml: ${msg}`)
}

const isStrings = (v: unknown): v is string[] => Array.isArray(v) && v.every(s => typeof s === 'string')

/** Parse and validate jiplak.yaml text; unknown keys are rejected so typos surface. */
export function loadConfig(text: string): Config {
  const raw: unknown = parse(text) ?? {}
  if (typeof raw !== 'object' || Array.isArray(raw)) fail('root must be a mapping')
  const c = { ...DEFAULTS, ...(raw as Record<string, unknown>) } as Record<string, unknown>
  const known = new Set([...Object.keys(DEFAULTS), ...THEME_KEYS, 'animate', 'channel'])
  for (const key of Object.keys(c)) if (!known.has(key)) fail(`unknown key "${key}"`)

  if (typeof c.url !== 'string' || !/^https?:\/\//.test(c.url)) fail('url must start with http:// or https://')
  if (!isStrings(c.routes) || c.routes.length === 0) fail('routes must be a non-empty list of paths')
  if (c.routes.some(r => !r.startsWith('/'))) fail('every route must start with "/"')
  if (typeof c.crawl !== 'boolean') fail('crawl must be true or false')
  if (!Number.isInteger(c.maxPages) || (c.maxPages as number) < 1) fail('maxPages must be a positive integer')
  if (!isStrings(c.ignore) || c.ignore.some(r => !r.startsWith('/'))) fail('ignore must be a list of paths starting with "/"')
  const bps = c.breakpoints
  if (!Array.isArray(bps) || bps.length === 0 || !bps.every(b => Number.isInteger(b) && b > 0))
    fail('breakpoints must be a non-empty list of positive integers')
  if (typeof c.out !== 'string' || c.out === '') fail('out must be a path')
  if (typeof c.wait !== 'number' || c.wait < 0) fail('wait must be a number >= 0')
  if (c.channel !== undefined && typeof c.channel !== 'string') fail('channel must be a string')
  if (!isStrings(c.cookies) || c.cookies.some(s => !s.includes('='))) fail('cookies must be a list of name=value')
  for (const key of THEME_KEYS) if (c[key] !== undefined && typeof c[key] !== 'string') fail(`${key} must be a string`)
  if (c.animate !== undefined && !ANIMATIONS.includes(c.animate as Animate))
    fail(`animate must be one of ${ANIMATIONS.join(', ')}`)

  return c as unknown as Config
}

export function themeOf(config: Config): Theme {
  const theme: Theme = {}
  for (const key of THEME_KEYS) if (config[key] !== undefined) theme[key] = config[key]
  if (config.animate) theme.animate = config.animate
  return theme
}

/** Source of the generated registry: imports every bones file and applies the yaml theme. */
export function registrySource(names: string[], theme: Theme): string {
  const sorted = [...names].sort()
  return [
    '// Generated by `jiplak build`. Do not edit.',
    "'use client'",
    '',
    `import { configureJiplak, registerBones${sorted.length > 0 ? ', type Bones' : ''} } from 'jiplak/react'`,
    ...sorted.map((n, i) => `import b${i} from './${n}.bones.json'`),
    '',
    `configureJiplak(${JSON.stringify(theme)})`,
    '',
    'registerBones({',
    ...sorted.map((n, i) => `  ${JSON.stringify(n)}: b${i} as unknown as Bones,`),
    '})',
    '',
  ].join('\n')
}

/** How the crawler uses `routes`: where to start, which links to follow, which to sample once. */
export interface RoutePlan {
  starts: string[]
  /** True when a crawled path may be visited (always true without glob routes). */
  allows: (path: string) => boolean
  /** The `*` pattern a path is one sample of, so only the first match is visited. */
  sampleOf: (path: string) => string | undefined
}

function globRegex(glob: string): RegExp {
  const body = glob
    .replace(/\/$/, '')
    .split('/')
    .map(seg => (seg === '**' ? '\u0000' : seg.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '[^/]+')))
    .join('/')
    .replace(/\/\u0000/g, '(?:/.*)?')
  return new RegExp(`^${body}$`)
}

export function routePlan(routes: string[]): RoutePlan {
  const globs = routes.filter(r => r.includes('*'))
  const matchers = globs.map(g => ({ glob: g, re: globRegex(g), sample: !g.includes('**') }))
  // A glob also starts at its fixed prefix (/id/entities/* at /id/entities, the page that links to
  // them), unless another glob already reaches that prefix by crawling.
  const prefixes = matchers
    .map(m => ({ glob: m.glob, prefix: m.glob.slice(0, m.glob.indexOf('*')).replace(/\/[^/]*$/, '') || '/' }))
    .filter(({ glob, prefix }) => !matchers.some(o => o.glob !== glob && o.re.test(prefix)))
    .map(({ prefix }) => prefix)
  return {
    starts: [...new Set([...routes.filter(r => !r.includes('*')), ...prefixes])],
    allows: path => matchers.length === 0 || matchers.some(m => m.re.test(path)),
    sampleOf: path => matchers.find(m => m.sample && m.re.test(path))?.glob,
  }
}

// Visiting these with a GET can end the session or download files.
const NEVER_VISIT = /(log-?out|sign-?out|keluar)(\/|$)|\.(pdf|zip|png|jpe?g|gif|svg|webp|mp4|csv|xlsx?)$/i

/** Same-origin paths from link hrefs worth crawling: no query/hash, no logout, no files, no ignored prefixes. */
export function crawlPaths(hrefs: string[], origin: string, ignore: string[]): string[] {
  const paths = new Set<string>()
  for (const href of hrefs) {
    let u: URL
    try {
      u = new URL(href, origin)
    } catch {
      continue
    }
    if (u.origin !== new URL(origin).origin) continue
    const path = u.pathname.replace(/(.)\/$/, '$1')
    if (NEVER_VISIT.test(path)) continue
    if (ignore.some(p => path === p || path.startsWith(p.replace(/\/$/, '') + '/'))) continue
    paths.add(path)
  }
  return [...paths]
}

/** Skeleton names become file names; keep them safe for the filesystem and imports. */
export const validName = (name: string) => /^[a-z0-9][a-z0-9-_]*$/i.test(name)
